# Assignment Operators
#You can update variables using assignment operators.
score = 1
#Instead of:
score = score + 10

#you can write:
score += 10

#Similarly:
score -= 5

#is equivalent to:
score = score - 5


#And:
score *= 2
#is equivalent to:
score = score * 2

#You can also use:
score /= 2
score = score / 2
# These operators become especially useful when working with loops.

