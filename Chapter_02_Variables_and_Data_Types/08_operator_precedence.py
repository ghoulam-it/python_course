#Python follows mathematical rules when evaluating expressions.For example:
result = 2 + 3 * 4

print(result)
# Output: 14 Not: 20
# Multiplication happens before addition.

#You can use parentheses to control the order:
result = (2 + 3) * 4

print(result)
Output:20

# A good habit is to use parentheses when they make your intention clearer.
