# Python can perform mathematical operations.
# Addition
result = 10 + 5
print(result)
#Output: 15


#Subtraction
result = 10 - 5
print(result)
#Output: 5


#Multiplication
result = 10 * 5
print(result)
#Output: 50


#Division
result = 10 / 5
print(result)
#Output:2.0
#Notice that / produces a floating-point result.


# Floor Division
#Python uses // for floor division.
result = 10 // 3

print(result)
# Output:3

#Regular division:
10 / 3
#produces approximately:3.3333333333333335
#Floor division gives:3
#We'll explore the exact behavior of floor division with negative numbers later.



#Exponents: Python uses ** for exponentiation.
result = 2 ** 3
print(result)
#Output:8
#Because:2 × 2 × 2 = 8

#You can also write:
square = 5 ** 2
cube = 5 ** 3



# Modulo
