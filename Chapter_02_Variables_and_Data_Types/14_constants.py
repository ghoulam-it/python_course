# Constants

# Python doesn't have a special keyword that makes a variable a true constant.
# However, Python programmers use uppercase names to indicate that a value should not normally be changed.

# For example:
PI = 3.14159
MAX_USERS = 100
TAX_RATE = 0.15

# The uppercase naming convention communicates:
# Treat this value as a constant.
# Python won't prevent you from changing it, however.
