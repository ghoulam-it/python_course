# Formatted Strings — f-Strings
# Python provides a convenient way to insert variables into strings.

#Consider:
name = "Mohamed"
age = 25
print(f"My name is {name} and I am {age} years old.")

#Output:My name is Ghoulam and I am 25 years old.
#The f before the string means it is an f-string.
#Inside {} you can put variables or expressions.

#For example:
price = 100
quantity = 3

print(f"Total: {price * quantity}")
#Output: Total: 300 F-strings are one of the most useful ways to format text in modern Python.
